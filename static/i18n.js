const STATUS_KEYS = {
    ouvert: "status_open",
    ferme: "status_closed",
    attente: "status_pending",
};

function getLang() {
    return localStorage.getItem("kasoft_lang") || "ar";
}

function setLang(lang) {
    localStorage.setItem("kasoft_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    applyI18n();
    document.dispatchEvent(new CustomEvent("kasoft:lang"));
}

function t(key) {
    const lang = getLang();
    return I18N[lang][key] || I18N.ar[key] || key;
}

function statusLabel(statusKey) {
    return t(STATUS_KEYS[statusKey] || statusKey);
}

function applyI18n() {
    const lang = getLang();
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.dataset.i18n;
        if (I18N[lang][key]) el.textContent = I18N[lang][key];
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
        const key = el.dataset.i18nHtml;
        if (I18N[lang][key]) el.innerHTML = I18N[lang][key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.dataset.i18nPlaceholder;
        if (I18N[lang][key]) el.placeholder = I18N[lang][key];
    });
    const titleEl = document.querySelector("title[data-i18n]");
    if (titleEl && I18N[lang][titleEl.dataset.i18n]) {
        document.title = I18N[lang][titleEl.dataset.i18n];
    }
    const toggle = document.getElementById("lang-toggle");
    if (toggle) toggle.textContent = t("lang_toggle");
}

document.addEventListener("DOMContentLoaded", () => {
    setLang(getLang());
    const toggle = document.getElementById("lang-toggle");
    if (toggle) {
        toggle.addEventListener("click", () => {
            setLang(getLang() === "ar" ? "fr" : "ar");
        });
    }
    if ("serviceWorker" in navigator) {
        navigator.serviceWorker.register("/sw.js?v=12").then((reg) => reg.update()).catch(() => {});
    }
});

window.KasoftI18n = { t, getLang, setLang, statusLabel, STATUS_KEYS, applyI18n };
